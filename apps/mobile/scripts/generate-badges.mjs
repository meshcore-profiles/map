// Renders the map marker badges (src/components/nodeImages.js + assets/nodes/*.png) from the website's node-types.svg,
// one per node type and update status. MapLibre needs raster images, Metro needs static require() paths, hence the generated module.
// Usage: npm run badges (from apps/mobile).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';
import { NODE_TYPE_ICON_NAMES, STATUS_COLORS } from '@meshcore-map/core/colors';

const SIZE = 96;
const SPRITE = readFileSync(new URL('../../web/public/icons/node-types.svg', import.meta.url), 'utf8');
const OUTPUT_DIR = new URL('../assets/nodes/', import.meta.url);
const MODULE_PATH = fileURLToPath(new URL('../src/components/nodeImages.js', import.meta.url));

const symbolBody = id => {
	const match = SPRITE.match(new RegExp(String.raw`<symbol id="${id}" viewBox="([^"]+)">([\s\S]*?)</symbol>`));
	if (!match) throw new Error(`Symbol "${id}" not found in node-types.svg`);

	return { viewBox: match[1], body: match[2] };
};

const render = (id, tint) => {
	const { viewBox, body } = symbolBody(id);
	const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="${SIZE}" height="${SIZE}">${tint(body)}</svg>`;

	return new Resvg(svg).render().asPng();
};

const names = [];

const write = (name, png) => {
	writeFileSync(new URL(`${name}.png`, OUTPUT_DIR), png);
	names.push(name);
};

mkdirSync(OUTPUT_DIR, { recursive: true });

for (const [type, id] of Object.entries(NODE_TYPE_ICON_NAMES)) {
	if (Number(type) === 1) continue;

	for (const [status, color] of Object.entries(STATUS_COLORS)) write(`${id}-${status}`, render(id, body => body.replaceAll('var(--node-color, #667b89)', color)));
}

// White person glyph drawn on a client's colored disc when its name has no letter the map font can render (e.g. an emoji).
write('client-glyph', render(`${NODE_TYPE_ICON_NAMES[1]}-plain`, body => body.replaceAll('currentColor', '#fff')));

const entries = names.map(name => `\t'${name}': require('../../assets/nodes/${name}.png'),`);
writeFileSync(MODULE_PATH, `// Generated by scripts/generate-badges.mjs from apps/web/public/icons/node-types.svg. Do not edit by hand.\nexport const NODE_IMAGES = {\n${entries.join('\n')}\n};\n`);
console.log(`Wrote ${names.length} badges`);
