// Generates src/ui/iconData.js from the website's SVG sprites, so the glyphs have a single source.
// Usage: npm run icons (from apps/mobile).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ICONS_DIR = new URL('../../web/public/icons/', import.meta.url);
const OUTPUT = fileURLToPath(new URL('../src/ui/iconData.js', import.meta.url));

const SYMBOL_RE = /<symbol\b([^>]*)>([\s\S]*?)<\/symbol>/g;
const ELEMENT_RE = /<([a-z]+)\b([^>]*?)\/>/g;
const ATTR_RE = /([A-Za-z][A-Za-z0-9-]*)="([^"]*)"/g;

const camel = name => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const pascal = tag => tag[0].toUpperCase() + tag.slice(1);
const parseAttrs = source => Object.fromEntries([...source.matchAll(ATTR_RE)].map(([, key, value]) => [key, value]));

const parseSprite = (file, filter) => {
	const result = {};
	for (const [, symbolAttrs, body] of readFileSync(new URL(file, ICONS_DIR), 'utf8').matchAll(SYMBOL_RE)) {
		const { id, viewBox, stroke, fill, 'stroke-width': strokeWidth } = parseAttrs(symbolAttrs);
		if (!filter(id)) continue;

		const nodes = [...body.matchAll(ELEMENT_RE)].map(([, tag, attrs]) => [
			pascal(tag),
			Object.fromEntries(Object.entries(parseAttrs(attrs)).map(([key, value]) => [camel(key), value])),
		]);

		const spec = { viewBox, nodes };
		if (stroke) Object.assign(spec, { stroke: true, strokeWidth: Number(strokeWidth) });
		else if (fill === 'currentColor') spec.fill = true;
		result[id] = spec;
	}

	return result;
};

const icons = { ...parseSprite('icons.svg', () => true), ...parseSprite('node-types.svg', id => id.endsWith('-plain')) };

const lines = Object.entries(icons).map(([name, spec]) => `\t'${name}': ${JSON.stringify(spec)},`);
writeFileSync(OUTPUT, `/* eslint-disable */\n// Generated by scripts/generate-icons.mjs from apps/web/public/icons/{icons,node-types}.svg. Do not edit by hand.\nexport const ICONS = {\n${lines.join('\n')}\n};\n`);
console.log(`Wrote ${lines.length} icons to ${OUTPUT}`);
